/** 주소→좌표: 네이버 주소 → 카카오 "구+이름" → 카카오 "이름" */
function geo3(string $addr, string $name, string $r2): array
{
    $clean = trim(preg_replace('/\(.*?\)/u', '', $addr));
    $r = GeoCoder::geocode('naver', $clean);
    if (!empty($r['ok'])) return ['lat' => (float)$r['lat'], 'lng' => (float)$r['lng'], 'via' => 'naver'];
    foreach ([trim($r2 . ' ' . $name), $name] as $q) {
        $kw = GeoCoder::searchKeyword($q, 1);
        if (!empty($kw['ok']) && !empty($kw['items'])) {
            $t = $kw['items'][0];
            return ['lat' => (float)$t['lat'], 'lng' => (float)$t['lng'], 'via' => 'kakao:' . $q];
        }
    }
    return ['lat' => null, 'lng' => null, 'via' => 'fail'];
}

